#!/usr/bin/env bash
# Role: 毎朝の求人サーチ。戎町（神戸市須磨区, 板宿駅至近）半径約500m以内の求人を【職種不問で】全件網羅し、
#        不足分を本社が兵庫・大阪・京都の在宅可求人で補完。計約50件。
#        Codex CLI で実行し、レポートを保存して GitHub(wirelessml/job-hunt-reports) に push する。
#        2026-06-07: 同志社（京都）・将棋/高槻 の優先枠を廃止し、戎町近辺onsite全件＋関西本社リモートの2本立てに集中。
#        2026-06-09: 在宅可(リモート)補完の優先順を「神戸市本社/拠点 → 兵庫県内 → 大阪市本社完全在宅 → 京都市本社完全在宅」に変更し、在宅実態(研修/機材/面談/定例出社)の確認を必須化。
#        2026-06-10朝: 対象を【事務職のみ】に変更。
#        2026-06-10午後: 事務職限定を解除し【全職種】に戻す（500m内は職種不問で全件網羅。実在・勤務地検証は維持）。
#        2026-06-10夜: 除外職種を恒久設定＝介護・福祉／障がい福祉支援職／飲食／保育士資格必須の保育士求人（ユーザー指定）。
set -u
DIR=/home/gci_admin/job-search-daily
mkdir -p "$DIR/reports"
cd "$DIR" || exit 1
DATE=$(date +%F)
REPORT="reports/job-report-$DATE.md"
PROMPT="あなたは求人サーチアシスタントです。Web検索を使って今日の求人を調べ、日本語の Markdown レポートを $DIR/$REPORT に書き出してください（ファイルを実際に作成・保存すること）。最優先は『戎町近辺（半径約500m以内）の求人を職種を問わず全件網羅』すること。そのうえで合計約50件に満たない場合のみ、在宅可求人で補完する。500mの範囲を広げて件数を稼ぐことは禁止。個人情報（氏名・住所・電話）は一切書かないこと。

【対象職種】原則すべての職種（雇用形態も問わない: 正社員・契約・派遣・パート・アルバイト）。ただし次の【除外職種】は載せない。
【除外職種】① 介護・福祉職（介護職員/ヘルパー/介護助手/介護福祉士/ケアマネージャー/生活相談員/サービス提供責任者など、訪問介護・グループホーム・デイサービス・老健等の介護系全般。介護施設内の看護職も除外）② 障がい者福祉の支援職（生活支援員/就労支援員/相談支援員など。ただし児童指導員・学童指導員・児童発達支援管理責任者は対象のまま）③ 飲食店スタッフ（調理/ホール/キッチン/接客。飲食企業の事務職は対象のまま）④ 保育士資格が必須の保育士求人（無資格可の保育補助・学童指導員・園の栄養士等は対象のまま）。除外職種で件数を埋めないこと。

【フィルタ】応募者は50代。年齢上限・生年要件で50代が応募不可と明記された求人は除外する。ただし応募者の年齢・属性そのものはレポート本文には書かないこと（個人情報）。

【実在・勤務地の検証（必須・二段階）】各求人はまず求人詳細ページ（Indeedならviewjob、求人ボックスなら/jb/等の個別ページ）を開くことを試み、(a)現在も応募可能な掲載 (b)勤務地の住所・最寄駅が条件範囲内 (c)会社名と職種の対応、の3点を確認する。確認できた求人は確認欄に『✔確認済』と書き、URLは詳細ページ直リンクを記載する。詳細ページがbot対策等で開けない場合でも、検索結果ページの求人カード自体に職種・会社名・勤務地・給与が明記されていれば掲載してよい。その場合は確認欄に『△未確認(詳細ページ取得不可)』と明記し、URLは検索結果ページを記載する。ただし『検索ページのタイトルや地域名（例:〈板宿駅の求人〉ページに出ているだけ）から勤務地を推定する』ことは禁止＝求人カード本文に勤務地が書かれているものだけを載せる。勤務地が確認できない求人は載せない。サマリーには『✔確認済 X件 / △未確認 Y件』の内訳も書く。

定義: 「戎町近辺」とは、神戸市須磨区戎町（地下鉄・山陽『板宿駅』至近）を中心とする半径約500m以内（徒歩おおむね6〜7分以内）の狭い範囲を指す。

手順（1 を最優先で全件網羅し、不足を 2 で補完）:
1. 【戎町近辺=半径500m以内・全職種を全件網羅（最優先）】『戎町近辺（戎町から半径約500m以内）』の求人を職種を問わず全件収集（全雇用形態。ただし上記【除外職種】は載せない）。目安町名: 戎町・飛松町・大黒町・大田町(駅寄り)・平田町(駅寄り)・前池町(駅寄り) 等、板宿駅至近のみ。500m超（養老町・千歳町・大池町の遠い部分・名谷・須磨海岸・新長田中心部・三宮 等）は含めない。件数稼ぎで範囲を広げてはいけないが、範囲内（500m以内）の求人は職種を問わず取りこぼさず網羅すること。各件: 職種 / 会社名または媒体 / 勤務地（駅・町名） / 雇用形態 / 給与 / 応募先URL。
2. 【50件に満たない分を在宅可（リモート/在宅）求人で補完。神戸市を最優先に次の優先順で並べる】手順1で50件に届かない場合、合計約50件になるまで在宅可求人を追加する（職種不問、ただし在宅デスクワークとして実態のあるもの。上記【除外職種】はここでも除外）。優先順位は必ず次の(1)→(2)→(3)→(4)の順とし、上位から先に埋め、上位が少ないときだけ下位に広げる:
   (1) 本社が神戸市、または神戸市内に勤務拠点・オフィス・勤務登録地がある在宅可求人【最優先】。
   (2) 本社または勤務拠点が神戸市以外の兵庫県内（明石・阪神間〔芦屋/西宮/尼崎〕等、神戸に近い順）の在宅可求人。
   (3) 本社が大阪市で、完全在宅または出社頻度が少ない（多くて月数回程度まで）の求人。
   (4) 本社が京都市で、完全在宅の求人。
   本社・拠点が関西（兵庫/大阪/京都）のいずれにも無い、東京等本社で全国どこでも可の純リモートは対象外。
   【在宅実態の確認（必須）】各求人は『在宅可』と書いてあっても鵜呑みにせず、研修期間中の出社有無・機材(PC等)が郵送か受取出社か・面談や入社手続きの来社有無・月次/週次の定常出社の有無を確認し明記する。定常的な出社が必要なものは出社頻度を明記し、出社頻度が高く実質在宅でないものは除外してよい。雇用形態が無期雇用派遣(SES)・客先常駐の場合はその旨も明記する。『フルリモート』が外回り直行直帰(訪問営業)を指す場合は在宅デスクワークではない旨を明記する。
   各件に次をセットで明記する: 職種 / 会社名 / 本社所在地(府県・市)と神戸拠点の有無 / 在宅条件(完全在宅か一部在宅か) / 出社頻度(研修・機材・面談・定例の出社) / 未経験可否 / 雇用形態 / 給与 / 応募先URL。条件を満たす求人が少なければ無理に50件にしなくてよい（条件優先）。
3. レポート冒頭にサマリー（戎町近辺(500m) X 件 / 在宅可(神戸優先, 本社=兵庫/大阪/京都) Y 件 / 合計 Z 件、今日の所感を2-3行。在宅可の内訳として 神戸市/兵庫県内/大阪市/京都市 の件数も書く）。本文は『戎町近辺の求人（半径500m以内・全職種）』『在宅可の求人（神戸市優先 → 兵庫県内 → 大阪市本社完全在宅 → 京都市本社完全在宅）』の2セクションに分ける。戎町近辺は表（確認[✔済/△未]/職種/会社名/勤務地/雇用形態/給与/URL）、在宅可は表（確認[✔済/△未]/優先区分[神戸市/兵庫/大阪/京都]/職種/会社名/本社所在地・神戸拠点/在宅条件/出社頻度/未経験/雇用形態/給与/URL）で、在宅可は上記(1)→(4)の優先順に並べる。末尾に検索に使ったURL一覧。

注意: 個人情報は書かない。応募の代行はしない（リスト化のみ）。誇張せず実在情報のみ。重複は除く。"
echo "=== daily-job-search start $(date -u +%FT%TZ) ==="
~/.local/bin/codex exec --skip-git-repo-check --sandbox workspace-write "$PROMPT" < /dev/null > "reports/codex-run-$DATE.log" 2>&1
RC=$?
echo "codex exit=$RC"
if [ ! -f "$REPORT" ]; then echo "REPORT_MISSING (see reports/codex-run-$DATE.log)"; exit 1; fi
echo "REPORT_OK $DIR/$REPORT ($(wc -l < "$REPORT") lines)"

# --- GitHub(wirelessml/job-hunt-reports) に push: Windows git.exe + gh 認証(setup-git済)を流用 ---
WINREPO_WSL=/mnt/c/Users/gci_admin/job-hunt-reports
WINREPO_WIN='C:\Users\gci_admin\job-hunt-reports'
if [ -d "$WINREPO_WSL/.git" ]; then
  cp -f "$REPORT" "$WINREPO_WSL/reports/" 2>/dev/null
  git.exe -C "$WINREPO_WIN" add reports >/dev/null 2>&1
  if git.exe -C "$WINREPO_WIN" -c user.name=wirelessml -c user.email=wirelessml@gmail.com commit -m "report: $DATE" >/dev/null 2>&1; then
    if git.exe -C "$WINREPO_WIN" push >/dev/null 2>&1; then echo "PUSHED $DATE"; else echo "PUSH_FAILED $DATE"; fi
  else
    echo "NO_CHANGE $DATE (nothing to commit)"
  fi
else
  echo "WINREPO not found; push skipped"
fi
